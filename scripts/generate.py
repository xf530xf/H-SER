def main():
    parser = argparse.ArgumentParser(description="Generate H²SER UCR batch commands")
    parser.add_argument('--output', type=Path, default=Path(__file__).with_name('ucr_cls.sh'))
    parser.add_argument('--entry', choices=['main_h2ser.py', 'train-net.py'], default='train-net.py')
    parser.add_argument('--cuda', default='cuda:0')
    args = parser.parse_args()
    import shlex
    lines = [
        '#!/usr/bin/env bash',
        'set -euo pipefail',
        'PROJECT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"',
        'cd "$PROJECT_DIR"',
        'PYTHON="${PYTHON:-python}"',
        '',
    ]
    for dataset in ucr_dataset_128:
        command = shlex.join([args.entry, '--dataset', dataset, '--save_csv_name',
                              'main_h2ser_results', '--cuda', args.cuda])
        lines.append(f'"$PYTHON" {command} "$@"')
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines) + '\n')
    print(f'Wrote {len(ucr_dataset_128)} H²SER commands to {args.output}')


if __name__ == '__main__':
    main()
